import Foundation

// MARK: - Lenient decoding (I4)

/// Decodes `Value`, or nil when the JSON is the wrong shape. Its `init` never
/// throws, so a bad `chapters`, `speakers` or `episodeTranscript` key drops
/// only itself and the song still decodes. A missing or `null` key never
/// reaches this type (`decodeIfPresent` returns nil first).
struct LenientValue<Value: Decodable & Sendable>: Decodable, Sendable {
    let value: Value?

    init(from decoder: Decoder) throws {
        value = try? Value(from: decoder)
    }
}

/// Decodes an array and keeps only the elements that decode, so one bad item
/// does not cost its siblings. A non-array value fails here, and the caller's
/// `LenientValue` turns that into nil.
struct LossyArray<Element: Decodable & Sendable>: Decodable, Sendable {
    let items: [Element]

    init(from decoder: Decoder) throws {
        var container = try decoder.unkeyedContainer()
        var kept: [Element] = []
        while !container.isAtEnd {
            let position = container.currentIndex
            if let item = try? container.decode(Element.self) {
                kept.append(item)
            } else {
                // A failed decode leaves the cursor on the bad element. Step past it,
                // and stop if even that does not move the cursor, so the loop always ends.
                _ = try? container.decode(SkippedElement.self)
                if container.currentIndex == position { break }
            }
        }
        items = kept
    }
}

/// Reads nothing, so it succeeds on any JSON value and only advances the cursor.
private struct SkippedElement: Decodable {
    init(from decoder: Decoder) throws {}
}

// MARK: - Wire shapes

/// One `chapters` item: `{ startMs, endMs, title }`. Only `startMs` is required,
/// so an item without it is dropped. `endMs` is optional because the last chapter
/// sends `null` when the server does not know the duration. `title` may be empty,
/// and a missing or non-string one reads as empty too.
struct ChapterDTO: Decodable, Sendable {
    let startMs: Int
    let endMs: Int?
    let title: String

    private enum CodingKeys: String, CodingKey {
        case startMs, endMs, title
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        startMs = try container.decode(Int.self, forKey: .startMs)
        endMs = try? container.decodeIfPresent(Int.self, forKey: .endMs)
        title = (try? container.decodeIfPresent(String.self, forKey: .title)) ?? ""
    }
}

/// One `speakers` item. `label` is the key the transcript file uses.
struct SpeakerDTO: Decodable, Sendable {
    let label: String?
    let name: String?
    let imageUrl: String?
    let creatorId: String?
}

/// `episodeTranscript`. The creator view adds `error` and `options`; they are
/// ignored here because listeners never receive them.
struct EpisodeTranscriptDTO: Decodable, Sendable {
    let status: String?
    let language: String?
    let source: String?
    let autoGenerated: Bool?
    let version: Int?
    let url: String?
    let offsetMs: Int?
}

// MARK: - Mapping

extension SongDTO {
    /// The episode timeline, or `nil` for anything that is not an episode, so
    /// music never carries one (contract rule 2).
    var resolvedEpisodeTimeline: EpisodeTimeline? {
        guard type == "episode" else { return nil }
        return EpisodeTimelineMapper.timeline(
            chapters: chapters?.value?.items ?? [],
            speakers: speakers?.value?.items ?? [],
            transcript: episodeTranscript?.value
        )
    }
}

/// Turns the wire shapes into the domain timeline. Each rule here is a contract
/// rule, so a client never needs to re-check it.
private enum EpisodeTimelineMapper {
    static let maxChapters = 200
    /// Contract: offsets are within ±60 s. Anything outside is clamped, not trusted.
    static let maxOffsetMs = 60_000

    static func timeline(
        chapters: [ChapterDTO],
        speakers: [SpeakerDTO],
        transcript: EpisodeTranscriptDTO?
    ) -> EpisodeTimeline {
        EpisodeTimeline(
            chapters: chapterList(from: chapters),
            speakers: speakerList(from: speakers),
            transcript: transcriptInfo(from: transcript)
        )
    }

    /// Sorted by start, bad items dropped, capped at 200, and empty unless at
    /// least two remain. An item with a negative start, or an end that is not
    /// after its start, is bad. A missing end on any chapter but the last takes
    /// the next chapter's start, which is what the server sends. The last one
    /// keeps a missing end, and the player's duration closes it later.
    private static func chapterList(from items: [ChapterDTO]) -> [EpisodeChapter] {
        let valid = items
            .filter { $0.startMs >= 0 && ($0.endMs ?? Int.max) > $0.startMs }
            .sorted { $0.startMs < $1.startMs }
            .prefix(maxChapters)
        let ordered = Array(valid)
        let chapters = ordered.enumerated().map { offset, item in
            let next = offset + 1 < ordered.count ? ordered[offset + 1].startMs : nil
            return EpisodeChapter(
                startMs: item.startMs,
                endMs: item.endMs ?? next,
                title: item.title.trimmingCharacters(in: .whitespacesAndNewlines)
            )
        }
        return chapters.count >= 2 ? chapters : []
    }

    /// Only labelled speakers are kept, in the order the server sent them.
    private static func speakerList(from items: [SpeakerDTO]) -> [EpisodeSpeaker] {
        items.compactMap { item in
            guard let label = cleaned(item.label) else { return nil }
            return EpisodeSpeaker(
                label: label,
                name: cleaned(item.name),
                imageURL: httpURL(cleaned(item.imageUrl)),
                creatorId: cleaned(item.creatorId)
            )
        }
    }

    private static func transcriptInfo(from dto: EpisodeTranscriptDTO?) -> EpisodeTranscriptInfo {
        guard let dto else { return .absent }
        let offset = min(max(dto.offsetMs ?? 0, -maxOffsetMs), maxOffsetMs)
        return EpisodeTranscriptInfo(
            status: EpisodeTranscriptStatus(rawValue: dto.status ?? "") ?? .absent,
            language: cleaned(dto.language),
            source: cleaned(dto.source),
            autoGenerated: dto.autoGenerated ?? false,
            version: dto.version ?? 0,
            url: httpURL(cleaned(dto.url)),
            offsetMs: offset
        )
    }

    /// Accepts only http and https, so a stray value cannot become a file or custom-scheme load.
    private static func httpURL(_ text: String?) -> URL? {
        guard let text, let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return nil }
        return scheme == "https" || scheme == "http" ? url : nil
    }

    /// Trimmed, and nil for empty or the literal "null"/"undefined" that some serializers leak.
    private static func cleaned(_ value: String?) -> String? {
        guard let value else { return nil }
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        let lower = trimmed.lowercased()
        if trimmed.isEmpty || lower == "null" || lower == "undefined" { return nil }
        return trimmed
    }
}
