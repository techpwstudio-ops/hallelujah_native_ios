#!/bin/sh
# Xcode Cloud post-clone step for the native iOS app.
#
# Xcode Cloud clones the repo and archives GHallelujah.xcodeproj with plain
# xcodebuild. The Xcode project and Package.resolved are committed, so there is
# no generator, no CocoaPods and no SDK to install. The only thing a clean clone
# lacks is the gitignored Config/Secrets.xcconfig (Base.xcconfig pulls it in
# last with `#include?`, so anything written there overrides the committed
# defaults). This script writes it from the workflow's environment variables.
#
# Workflow environment variables (Xcode Cloud workflow -> Environment; tick
# "Secret" on every one except the two version overrides):
#   HALLELUJAH_DEVELOPMENT_TEAM  required  Apple Developer Team ID (10 chars)
#   HALLELUJAH_API_SECRET        required for the Production scheme (backend "secure" header)
#   HALLELUJAH_OTP_SECRET_1      required for the Production scheme
#   HALLELUJAH_OTP_SECRET_2      required for the Production scheme
#   RAZORPAY_KEY_ID              optional
#   CLARITY_PROJECT_ID           optional
#   IOS_MARKETING_VERSION        optional   CFBundleShortVersionString; unset keeps
#                                           MARKETING_VERSION from Config/Shared/Base.xcconfig.
#                                           App Store Connect rejects a version that does not
#                                           increase, so bump it for every App Store release.
#   BUILD_NUMBER_OFFSET          optional   added to $CI_BUILD_NUMBER (default 0), for when the
#                                           listing already has higher build numbers.
#
# Firebase needs no GoogleService-Info.plist: FirebaseBootstrap builds the
# options in code from the xcconfig environment.

set -eu

cd "$CI_PRIMARY_REPOSITORY_PATH"

SECRETS=Config/Secrets.xcconfig

fail() {
  echo "error: $1" >&2
  exit 1
}

[ -n "${HALLELUJAH_DEVELOPMENT_TEAM:-}" ] || fail "HALLELUJAH_DEVELOPMENT_TEAM is not set — add your Apple Team ID as a workflow environment variable."

# Release builds talk to production and are useless without these.
case "${CI_XCODE_SCHEME:-}" in
  *Production*)
    [ -n "${HALLELUJAH_API_SECRET:-}" ] || fail "HALLELUJAH_API_SECRET is not set (required for the Production scheme)."
    [ -n "${HALLELUJAH_OTP_SECRET_1:-}" ] || fail "HALLELUJAH_OTP_SECRET_1 is not set (required for the Production scheme)."
    [ -n "${HALLELUJAH_OTP_SECRET_2:-}" ] || fail "HALLELUJAH_OTP_SECRET_2 is not set (required for the Production scheme)."
    ;;
esac

BUILD_NUMBER=$(( ${CI_BUILD_NUMBER:-1} + ${BUILD_NUMBER_OFFSET:-0} ))

{
  echo "// Generated by ci_scripts/ci_post_clone.sh — never committed."
  echo "HALLELUJAH_DEVELOPMENT_TEAM = $HALLELUJAH_DEVELOPMENT_TEAM"
  echo "HALLELUJAH_API_SECRET = ${HALLELUJAH_API_SECRET:-}"
  echo "HALLELUJAH_OTP_SECRET_1 = ${HALLELUJAH_OTP_SECRET_1:-}"
  echo "HALLELUJAH_OTP_SECRET_2 = ${HALLELUJAH_OTP_SECRET_2:-}"
  echo "RAZORPAY_KEY_ID = ${RAZORPAY_KEY_ID:-}"
  echo "CLARITY_PROJECT_ID = ${CLARITY_PROJECT_ID:-}"
  echo "CURRENT_PROJECT_VERSION = $BUILD_NUMBER"
  if [ -n "${IOS_MARKETING_VERSION:-}" ]; then
    echo "MARKETING_VERSION = $IOS_MARKETING_VERSION"
  fi
} > "$SECRETS"

echo "Wrote $SECRETS (scheme: ${CI_XCODE_SCHEME:-unknown}, build $BUILD_NUMBER, version ${IOS_MARKETING_VERSION:-from Base.xcconfig})"
echo "ci_post_clone.sh completed"
