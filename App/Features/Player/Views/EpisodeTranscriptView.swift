import SwiftUI

/// The full transcript of an episode (Phase 2). One paragraph per transcript
/// segment, with a speaker header when the speaker changes (two or more speakers
/// only). The word being spoken is highlighted and followed. Scrolling by hand
/// stops following until "Back to current" is tapped. Tapping a word seeks to it.
/// Like the lyrics screen, it has its own scrubber and play button.
struct EpisodeTranscriptView: View {
    @Environment(\.dismiss) private var dismiss
    @State private var engine: AudioEngine = DependencyContainer.current.resolve()
    @State private var store: EpisodeTimelineStore = DependencyContainer.current.resolve()
    @State private var isFollowing = true

    private static let followAnchor = UnitPoint(x: 0.5, y: 0.35)
    private static let scrollAnimation = Animation.easeOut(duration: 0.35)

    private var activeWord: Int? { store.clock.activeWordIndex }

    private var activeSegment: Int? {
        guard let activeWord else { return nil }
        return store.index?.segmentIndex(forWord: activeWord)
    }

    var body: some View {
        VStack(spacing: 0) {
            if let file = store.transcript {
                transcript(file)
            } else {
                Color.clear
            }
            controls
        }
        .background(PlayerStyle.black.ignoresSafeArea())
        .toolbar {
            AppBackToolbarItem { dismiss() }
            ToolbarItem(placement: .principal) {
                Text("Transcript")
                    .typography(Typography.titleMedium)
                    .foregroundStyle(PlayerStyle.white)
            }
        }
        .navigationBarTitleDisplayMode(.inline)
        .navigationBarBackButtonHidden(true)
        .toolbarBackground(PlayerStyle.black, for: .navigationBar)
        .toolbarBackground(.visible, for: .navigationBar)
        .toolbarColorScheme(.dark, for: .navigationBar)
        .onAppear { store.clock.clientAppeared() }
        .onDisappear { store.clock.clientDisappeared() }
    }

    private func transcript(_ file: EpisodeTranscriptFile) -> some View {
        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 24) {
                    ForEach(file.segments.indices, id: \.self) { segmentIndex in
                        paragraph(file: file, segmentIndex: segmentIndex)
                            .id(segmentIndex)
                    }
                    if store.timeline?.transcript.autoGenerated == true {
                        Text("Auto-generated")
                            .typography(PlayerStyle.timeLabel)
                            .foregroundStyle(PlayerStyle.whiteAlpha(0.6))
                    }
                }
                .padding(.horizontal, PlayerStyle.pageSidePadding)
                .padding(.vertical, 16)
                .readableContentWidth()
            }
            .simultaneousGesture(
                DragGesture(minimumDistance: 8).onChanged { _ in isFollowing = false }
            )
            .overlay(alignment: .bottom) {
                if !isFollowing {
                    backToCurrentButton(proxy: proxy)
                        .padding(.bottom, 16)
                }
            }
            .onChange(of: activeSegment) { _, _ in
                follow(proxy)
            }
            .onChange(of: isFollowing) { _, following in
                if following { follow(proxy) }
            }
            .onAppear { follow(proxy) }
        }
    }

    @ViewBuilder
    private func paragraph(file: EpisodeTranscriptFile, segmentIndex: Int) -> some View {
        let segment = file.segments[segmentIndex]
        VStack(alignment: .leading, spacing: 10) {
            if store.hasMultipleSpeakers, let speaker = segment.speaker,
               segmentIndex == 0 || file.segments[segmentIndex - 1].speaker != speaker {
                speakerHeader(label: speaker)
            }
            TranscriptParagraphView(
                words: Array(file.words[segment.wordRange]),
                firstWordIndex: segment.wordRange.lowerBound,
                state: paragraphState(for: segment.wordRange),
                onWordTap: { wordIndex in seek(toWord: wordIndex, in: file) }
            )
            .equatable()
        }
    }

    /// Spoken paragraphs before the active word, upcoming ones after it. The active
    /// paragraph carries the word's offset, so only it re-renders as the word moves.
    private func paragraphState(for range: Range<Int>) -> TranscriptParagraphView.State {
        guard let activeWord else { return .upcoming }
        if activeWord < range.lowerBound { return .upcoming }
        if activeWord >= range.upperBound { return .spoken }
        return .active(wordOffset: activeWord - range.lowerBound)
    }

    private func speakerHeader(label: String) -> some View {
        let speaker = store.speakers.first { $0.label == label }
        return HStack(spacing: 10) {
            ArtworkView(url: speaker?.imageURL, width: 32, height: 32, cornerRadius: 16)
            Text(speakerName(for: label))
                .typography(Typography.titleSmall)
                .foregroundStyle(PlayerStyle.white)
        }
    }

    /// The server's name, else "Speaker N" from the label's place in the speakers list.
    private func speakerName(for label: String) -> String {
        guard let position = store.speakerPosition(forLabel: label) else { return label }
        return store.speakers[position].name ?? String(localized: "Speaker \(position + 1)")
    }

    private func backToCurrentButton(proxy: ScrollViewProxy) -> some View {
        Button {
            isFollowing = true
        } label: {
            Text("Back to current")
                .typography(PlayerStyle.timeLabel)
                .foregroundStyle(PlayerStyle.white)
                .padding(.horizontal, 20)
                .padding(.vertical, 8)
                .background(PlayerStyle.whiteAlpha(0.16), in: Capsule())
        }
        .buttonStyle(.plain)
    }

    private func follow(_ proxy: ScrollViewProxy) {
        guard isFollowing, let activeSegment else { return }
        withAnimation(Self.scrollAnimation) {
            proxy.scrollTo(activeSegment, anchor: Self.followAnchor)
        }
    }

    /// Seeks to the word's start. The word's player time is its file time plus `offsetMs`.
    private func seek(toWord wordIndex: Int, in file: EpisodeTranscriptFile) {
        guard file.startsMs.indices.contains(wordIndex) else { return }
        engine.seek(to: Double(file.startsMs[wordIndex] + store.offsetMs) / 1000)
    }

    private var controls: some View {
        VStack(spacing: 0) {
            PlayerSeekBar(
                position: engine.currentPosition,
                duration: engine.currentItemDuration ?? TimeInterval(engine.currentSong?.duration ?? 0),
                barHeight: 4,
                chapters: store.chapters
            ) { target in
                engine.seek(to: target)
            }
            .readableContentWidth()
            .padding(.top, 16)

            Button {
                if engine.status == .playing { engine.pause() } else { engine.resume() }
            } label: {
                PlayerPlayPauseDisc(
                    isPlaying: engine.status == .playing,
                    isLoading: engine.status == .loading,
                    diameter: 48,
                    glyphSize: 32
                )
            }
            .buttonStyle(.plain)
            .padding(.top, 16)
        }
        .padding(.horizontal, PlayerStyle.pageSidePadding)
        .padding(.top, 8)
        .padding(.bottom, 24)
    }
}
