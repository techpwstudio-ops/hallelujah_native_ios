import Foundation

/// One chapter of an episode (`chapters` in the song detail, contract §3).
/// `endMs` is the next chapter's `startMs`; the last one ends at the duration.
struct EpisodeChapter: Sendable, Equatable, Identifiable {
    let id: String
    let startMs: Int
    let endMs: Int
    let title: String
    let imageURL: URL?
    let linkURL: URL?
}

/// One speaker label that appears in the transcript (`speakers`, contract §3).
/// `name` is nil until someone names the speaker; the app then shows "Speaker N".
struct EpisodeSpeaker: Sendable, Equatable {
    let label: String
    let name: String?
    let imageURL: URL?
    let creatorId: String?
}

/// `episodeTranscript.status`. A value the app does not know reads as `absent`,
/// so no transcript UI is shown for it.
enum EpisodeTranscriptStatus: String, Sendable, Equatable {
    case absent = "none"
    case queued
    case processing
    case ready
    case failed
}

/// `episodeTranscript` (contract §3). `offsetMs` shifts the transcript's word
/// times: a word's effective time is its file time plus `offsetMs`.
struct EpisodeTranscriptInfo: Sendable, Equatable {
    let status: EpisodeTranscriptStatus
    let language: String?
    let source: String?
    let autoGenerated: Bool
    let version: Int
    let url: URL?
    let offsetMs: Int

    static let absent = EpisodeTranscriptInfo(
        status: .absent,
        language: nil,
        source: nil,
        autoGenerated: false,
        version: 0,
        url: nil,
        offsetMs: 0
    )
}

/// The episode-only data the player shows beside the audio. Present on
/// `Song.episodeTimeline` for episodes only; `nil` for music.
struct EpisodeTimeline: Sendable, Equatable {
    /// Empty unless the episode has at least two valid chapters (rule R2).
    let chapters: [EpisodeChapter]
    let speakers: [EpisodeSpeaker]
    let transcript: EpisodeTranscriptInfo
}
