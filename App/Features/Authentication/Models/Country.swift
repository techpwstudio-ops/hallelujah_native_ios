    let dialCode: String

    var id: String { isoCode }

    /// `Country.flagEmoji` (the package's `country.dart`): built from the
    /// ISO2 code via Unicode regional indicator symbols, not a stored asset
    /// — the same computation as the Dart package's
    /// `Utils.countryCodeToEmoji`. Every `isoCode` in `all` is exactly two
    /// uppercase ASCII letters, so this always produces a flag.
    var flagEmoji: String {
        let base: UInt32 = 0x1F1E6
        let aValue = Unicode.Scalar("A").value
        let zValue = Unicode.Scalar("Z").value

        var flag = ""
        for scalar in isoCode.unicodeScalars {
            guard scalar.value >= aValue, scalar.value <= zValue,
                  let regionalIndicator = Unicode.Scalar(base + (scalar.value - aValue)) else { continue }
            flag.unicodeScalars.append(regionalIndicator)
        }
        return flag
    }

    var dialCodeDisplay: String { "+\(dialCode)" }

