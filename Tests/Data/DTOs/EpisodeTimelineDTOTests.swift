import Foundation
import Testing
@testable import Hallelujah

/// Decoding of the episode fields against the backend contract fixtures, plus bad input.
struct EpisodeTimelineDTOTests {
    private func decodeSong(_ name: String) throws -> Song {
        let data = try EpisodeTimelineFixtures.data(named: name)
        return try JSONDecoder().decode(SongDetailResponseDTO.self, from: data).data.toDomain()
    }

    /// An episode-typed song whose `fields` replace the new keys, so a test can break one at a time.
    private func episodeData(_ fields: String) -> Data {
        Data("""
        {"data": {"id": "e1", "title": "Episode", "type": "episode", "transcripts": [], \(fields)}}
        """.utf8)
    }

    private func decodeEpisode(_ fields: String) throws -> Song {
        try JSONDecoder().decode(SongDetailResponseDTO.self, from: episodeData(fields)).data.toDomain()
    }

    @Test func episodeFixtureDecodesChaptersSpeakersAndTranscript() throws {
        let song = try decodeSong("song-detail-episode")
        let timeline = try #require(song.episodeTimeline)

        #expect(timeline.chapters.map(\.startMs) == [0, 74_000, 1_500_000, 3_000_000])
        #expect(timeline.chapters[0].title == "Intro")
        #expect(timeline.chapters[1].imageURL?.absoluteString == "https://cdn.example.com/chapters/storm.jpg")
        #expect(timeline.chapters[1].linkURL?.absoluteString == "https://www.bible.com/bible/111/MRK.4.35-41")
        #expect(timeline.chapters[3].title == "ప్రార్థన (Prayer)")

        #expect(timeline.speakers.map(\.label) == ["S1", "S2"])
        #expect(timeline.speakers[0].name == "Pastor John")
        #expect(timeline.speakers[1].name == nil)

        #expect(timeline.transcript.status == .ready)
        #expect(timeline.transcript.language == "te")
        #expect(timeline.transcript.autoGenerated)
        #expect(timeline.transcript.version == 2)
        #expect(timeline.transcript.offsetMs == 0)
        #expect(timeline.transcript.url != nil)
    }

    @Test func minimalEpisodeFixtureHasNoNewData() throws {
        let song = try decodeSong("song-detail-episode-minimal")
        let timeline = try #require(song.episodeTimeline)

        #expect(timeline.chapters.isEmpty)
        #expect(timeline.speakers.isEmpty)
        #expect(timeline.transcript.status == .absent)
        #expect(timeline.transcript.url == nil)
    }

    @Test func musicFixtureProducesNoTimeline() throws {
        let song = try decodeSong("song-detail-music")

        #expect(song.episodeTimeline == nil)
        #expect(song.transcripts?.first?.id == "l1")
    }

    @Test func creatorFixtureDecodesTheListenerFields() throws {
        let song = try decodeSong("creator-song-detail-episode")
        let timeline = try #require(song.episodeTimeline)

        #expect(timeline.chapters.count == 4)
        #expect(timeline.speakers.count == 2)
        #expect(timeline.transcript.status == .ready)
    }

    @Test func chaptersAsAStringDropOnlyTheChapters() throws {
        let song = try decodeEpisode(#""chapters": "oops", "speakers": [], "episodeTranscript": {"status": "none"}"#)

        #expect(song.title == "Episode")
        #expect(song.episodeTimeline?.chapters.isEmpty == true)
    }

    @Test func oneBadChapterIsDroppedAndTheRestKept() throws {
        let chapters = """
        "chapters": [
          {"startMs": 0, "endMs": 5000, "title": "Intro"},
          {"endMs": 9000, "title": "No start"},
          {"startMs": 5000, "endMs": 9000, "title": "Main"}
        ]
        """
        let song = try decodeEpisode(chapters + #", "episodeTranscript": {"status": "none"}"#)

        #expect(song.episodeTimeline?.chapters.map(\.title) == ["Intro", "Main"])
    }

    @Test func chaptersAreSortedAndNeedAtLeastTwoToShow() throws {
        let twoOutOfOrder = """
        "chapters": [
          {"startMs": 5000, "endMs": 9000, "title": "Second"},
          {"startMs": 0, "endMs": 5000, "title": "First"}
        ]
        """
        let sorted = try decodeEpisode(twoOutOfOrder)
        #expect(sorted.episodeTimeline?.chapters.map(\.title) == ["First", "Second"])

        let single = try decodeEpisode(#""chapters": [{"startMs": 0, "endMs": 5000, "title": "Only"}]"#)
        #expect(single.episodeTimeline?.chapters.isEmpty == true)
    }

    @Test func unknownTranscriptStatusReadsAsAbsent() throws {
        let song = try decodeEpisode(#""episodeTranscript": {"status": "later", "version": 3}"#)

        #expect(song.episodeTimeline?.transcript.status == .absent)
    }

    @Test func malformedTranscriptObjectDropsOnlyTheTranscript() throws {
        let song = try decodeEpisode(#""chapters": [], "episodeTranscript": "broken""#)

        #expect(song.title == "Episode")
        #expect(song.episodeTimeline?.transcript == .absent)
    }

    @Test func nonHttpURLsAreNotKept() throws {
        let song = try decodeEpisode(#""episodeTranscript": {"status": "ready", "url": "file:///etc/passwd"}"#)

        #expect(song.episodeTimeline?.transcript.url == nil)
    }

    @Test func offsetIsClampedToSixtySeconds() throws {
        let song = try decodeEpisode(#""episodeTranscript": {"status": "none", "offsetMs": 999999}"#)

        #expect(song.episodeTimeline?.transcript.offsetMs == 60_000)
    }
}
