    /// separate, non-deduplicated render sections, so India renders twice —
    /// once pinned here, once again at its natural alphabetical position
    /// below. `CountryPickerView` reproduces that exactly rather than
    /// "fixing" it.
    static var favorites: [Country] {
        all.filter { favoriteISOCodes.contains($0.isoCode) }
    }

